"""SQLite historian: durable simulated telemetry, separate events and operator annotations.

No SQL or API permits modifying physical equipment. Does not accept arbitrary external
records; validation requires data_source='synthetic' and explicit schema version.
"""
import json
import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from .schema import validate_record

DEFAULT_DB = Path(os.environ.get('DEWATERIQ_DB', str(Path(__file__).resolve().parents[1] / 'data' / 'dewateriq.sqlite3')))

@contextmanager
def connection(path=None):
    p = Path(path or DEFAULT_DB)
    p.parent.mkdir(parents=True, exist_ok=True)
    db = sqlite3.connect(str(p), timeout=30)
    db.row_factory = sqlite3.Row
    db.execute('PRAGMA busy_timeout=30000')
    db.execute('PRAGMA journal_mode=WAL')
    try:
        db.executescript('''
        CREATE TABLE IF NOT EXISTS telemetry (
          run_id TEXT NOT NULL, centrifuge_id TEXT NOT NULL,
          timestamp_s INTEGER NOT NULL, scenario TEXT NOT NULL,
          mode TEXT NOT NULL, source TEXT NOT NULL, json_text TEXT NOT NULL,
          PRIMARY KEY(run_id,centrifuge_id,timestamp_s));
        CREATE INDEX IF NOT EXISTS ix_telemetry_scenario ON telemetry(scenario);
        CREATE TABLE IF NOT EXISTS events (
          run_id TEXT NOT NULL, centrifuge_id TEXT NOT NULL,
          timestamp_s INTEGER NOT NULL, event_type TEXT NOT NULL,
          details TEXT NOT NULL,
          PRIMARY KEY(run_id,centrifuge_id,timestamp_s,event_type));
        CREATE TABLE IF NOT EXISTS operator_notes (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          run_id TEXT NOT NULL, timestamp_s INTEGER NOT NULL,
          observation TEXT NOT NULL, cut_quality TEXT NOT NULL,
          created_utc TEXT NOT NULL DEFAULT (datetime('now')));
        ''')
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


def insert_records(records, path=None):
    count=0
    with connection(path) as db:
        for r in records:
            validate_record(r)
            raw = json.dumps(r, separators=(',', ':'), sort_keys=True)
            db.execute('INSERT OR REPLACE INTO telemetry VALUES(?,?,?,?,?,?,?)',
                       (r['run_id'], r['centrifuge_id'], r['timestamp_s'],
                        r['scenario'], r['operating_mode'], r['data_source'], raw))
            observed=set()
            for event in (r['event'], r['fault']):
                if event != 'none': observed.add(event)
            for event in observed:
                db.execute('INSERT OR REPLACE INTO events VALUES(?,?,?,?,?)',
                           (r['run_id'],r['centrifuge_id'],r['timestamp_s'], event,
                            'Generated by deterministic synthetic simulator'))
            count+=1
    return count


def runs(path=None):
    with connection(path) as db:
        return [dict(x) for x in db.execute('''SELECT run_id, scenario, mode,
          COUNT(*) AS samples, MAX(timestamp_s) AS last_second
          FROM telemetry GROUP BY run_id,scenario,mode ORDER BY run_id''').fetchall()]


def get_run(run_id, path=None):
    with connection(path) as db:
        rows=db.execute('SELECT json_text FROM telemetry WHERE run_id=? ORDER BY timestamp_s',
                        (run_id,)).fetchall()
        return [json.loads(x[0]) for x in rows]


def get_events(run_id, path=None):
    with connection(path) as db:
        return [dict(x) for x in db.execute('SELECT * FROM events WHERE run_id=? ORDER BY timestamp_s',(run_id,)).fetchall()]


def add_note(run_id, timestamp_s, observation, cut_quality='unknown', path=None):
    if len(observation.strip())==0 or len(observation)>1000: raise ValueError('Note must be 1-1000 characters')
    if cut_quality not in ('unknown','very_wet','wet','acceptable','dry','very_dry'):
        raise ValueError('Unsupported cut-quality label')
    if not get_run(run_id,path): raise ValueError('Unknown run')
    with connection(path) as db:
        db.execute('INSERT INTO operator_notes (run_id,timestamp_s,observation,cut_quality) VALUES(?,?,?,?)',
                   (run_id,int(timestamp_s),observation,cut_quality))


def get_notes(run_id, path=None):
    with connection(path) as db:
        return [dict(x) for x in db.execute('SELECT * FROM operator_notes WHERE run_id=? ORDER BY timestamp_s,id',(run_id,)).fetchall()]
